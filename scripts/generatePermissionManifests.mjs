#!/usr/bin/env node
// Regenerates each function's server-side copy of src/lib/permissionRegistry.js
// (Module 3). Base44/Deno isolates every function directory -- they can't
// import a sibling module -- so each function that needs the registry gets a
// generated, identical copy rather than a hand-maintained one that can drift.
//
// Run this after any change to src/lib/permissionRegistry.js, before
// committing. CI (once wired) re-runs it and fails the build on a diff.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const registryPath = path.join(root, "src/lib/permissionRegistry.js");

// Functions whose entry.ts needs the registry to re-check a write path
// server-side (Module 3). Family/content aren't written yet (Phase 3 is
// still in progress) -- this list grows as those land; running the
// generator against a target that doesn't exist yet is a no-op, not an
// error, so this script can run safely from any point in the phase.
const TARGET_FUNCTION_DIRS = ["family", "content"];

const registrySource = readFileSync(registryPath, "utf8");
// Lift the registry object literal itself out of the source rather than
// re-deriving it by hand -- the generated copy must be the same data, not a
// re-typed approximation of it.
const match = registrySource.match(
  /export const PERMISSION_REGISTRY = Object\.freeze\((\{[\s\S]*?\})\);/,
);
if (!match) {
  console.error("Could not find PERMISSION_REGISTRY in src/lib/permissionRegistry.js");
  process.exit(1);
}
const registryLiteral = match[1];

const header = `// GENERATED by scripts/generatePermissionManifests.mjs from
// src/lib/permissionRegistry.js -- never hand-edit. Regenerate after any
// change to the source registry, before committing.

export const PERMISSION_REGISTRY: Record<string, Record<string, string[]>> = ${registryLiteral};

export function defaultAllowed(section: string, action: string, role: string): boolean {
  return PERMISSION_REGISTRY[section]?.[action]?.includes(role) ?? false;
}
`;

let written = 0;
let skipped = 0;
for (const dir of TARGET_FUNCTION_DIRS) {
  const dirPath = path.join(root, "base44/functions", dir);
  if (!existsSync(dirPath)) {
    console.log(`skip (no such function dir yet): ${dir}`);
    skipped++;
    continue;
  }
  const outPath = path.join(dirPath, "_permissions.generated.ts");
  writeFileSync(outPath, header);
  console.log(`wrote base44/functions/${dir}/_permissions.generated.ts`);
  written++;
}

console.log(`\n${written} written, ${skipped} skipped.`);
